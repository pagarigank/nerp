using ERP.Shared.Kernel.Documents;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace ERP.Reporting;

/// <summary>
/// Generic tabular report PDF: title, optional subtitle, header row, then data rows.
/// Reuses <see cref="DocumentHeader"/> for company/customer header + page footer.
/// Shared across all modules (OM, Purchasing, Inventory, etc.).
/// </summary>
public sealed class ReportDocument(
    CompanyDocumentHeader header,
    string title,
    string? subtitle,
    IReadOnlyList<(string[] Headers, string[][] Rows)> tables,
    decimal? totalAmount,
    string? totalLabel) : IDocument
{
    private static IContainer HeaderCellStyle(IContainer c) => c.PaddingVertical(4).PaddingHorizontal(2).Background(Colors.Grey.Lighten3);
    private static IContainer BodyCellStyle(IContainer c) => c.PaddingVertical(3).PaddingHorizontal(2).BorderBottom(1).BorderColor(Colors.Grey.Lighten2);

    public DocumentMetadata GetMetadata() => DocumentMetadata.Default;

    public void Compose(IDocumentContainer container)
    {
        container.Page(page =>
        {
            page.Margin(40);
            page.Size(PageSizes.A4);
            page.DefaultTextStyle(x => x.FontSize(9));
            page.Header().Element(x => DocumentHeader.Header(x, header));
            page.Content().PaddingVertical(10).Element(BuildContent);
            page.Footer().Element(x => DocumentHeader.Footer(x));
        });
    }

    private void BuildContent(IContainer container)
    {
        container.Column(col =>
        {
            col.Item().Text(title).SemiBold().FontSize(20);
            if (!string.IsNullOrEmpty(subtitle))
                col.Item().Text(subtitle).FontSize(10).FontColor(Colors.Grey.Darken2);
            col.Item().PaddingVertical(4).LineHorizontal(1).LineColor(Colors.Grey.Lighten2);

            foreach (var (headers, rows) in tables)
            {
                col.Item().PaddingTop(8).Table(t =>
                {
                    t.ColumnsDefinition(cd =>
                    {
                        for (var i = 0; i < headers.Length; i++)
                        {
                            cd.RelativeColumn(i == 0 ? 1.4f : 1f);
                        }
                    });

                    t.Header(h =>
                    {
                        foreach (var hText in headers)
                        {
                            h.Cell().Element(HeaderCellStyle).Text(hText).SemiBold().FontSize(8);
                        }
                    });

                    if (rows.Length == 0)
                    {
                        t.Cell().Element(BodyCellStyle).Text("(no records)").FontSize(8).FontColor(Colors.Grey.Darken2);
                    }
                    else
                    {
                        foreach (var row in rows)
                        {
                            for (var j = 0; j < row.Length; j++)
                            {
                                t.Cell().Element(BodyCellStyle).Text(row[j]).FontSize(8);
                            }
                        }
                    }
                });
            }

            if (totalAmount.HasValue && !string.IsNullOrEmpty(totalLabel))
            {
                col.Item().PaddingTop(10).Row(r =>
                {
                    r.RelativeItem().Text(totalLabel).FontSize(9).SemiBold();
                    r.RelativeItem().AlignRight().Text($"${totalAmount.Value:N2}").FontSize(9).SemiBold();
                });
            }

            col.Item().PaddingTop(14).Text("Generated by ERP — Report").FontSize(8).FontColor(Colors.Grey.Darken2);
        });
    }
}
